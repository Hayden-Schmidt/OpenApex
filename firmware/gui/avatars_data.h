// Preset avatars from design/avatars (docs/OpenApex_SPEC.md §5.5). Each keeps the artist's
// pixels and a small palette. Themed entries follow the accent: the character's main colour is the
// accent's hue at main_s/main_v times the accent's saturation/brightness, and every other themed
// colour is the main colour turned by dh degrees with saturation and brightness scaled by s/64 and
// v/64; the outline is a dark themed entry so it stays visible on black. Fixed entries (pupils,
// eye whites, beaks, feet) are plain RGB and never change.
// Pixels are 4 bits, high nibble first; 0 is transparent and n is palette entry n - 1.
