int main(void)
{
    raw_notif_t p;

    memset(&p, 0, sizeof(p));
    assert(packet_decode(k_v5_android, RAW_NOTIF_PACKET_SIZE, &p));
    assert(p.sequence == 7U);
    assert(p.gnss_fix_valid);
    assert(!p.source_is_ios);
    /* v5 predates the groups, so a v5 packet must count as carrying both halves. */
    assert((p.source_groups & RAW_GROUP_NAV) != 0U);
    assert((p.source_groups & RAW_GROUP_TELEMETRY) != 0U);
    assert(strcmp(p.title_str, "Turn left") == 0);
    assert(strcmp(p.distance_str, "200 m") == 0);
    assert(strcmp(p.eta_str, "10 min") == 0);
    assert(p.speed_kmh_x10 == 420U);
    assert(p.heading_deg == 90U);
    assert(p.battery_percent == 80U);

    memset(&p, 0, sizeof(p));
    assert(packet_decode(k_v6_ios, RAW_NOTIF_PACKET_SIZE, &p));
    assert(p.sequence == 7U);
    assert(p.gnss_fix_valid);
    assert(p.source_is_ios);
    /* The whole point of v6: telemetry only, so the merge must not let it blank ANCS nav. */
    assert((p.source_groups & RAW_GROUP_NAV) == 0U);
    assert((p.source_groups & RAW_GROUP_TELEMETRY) != 0U);
    assert(p.title_str[0] == 0);
    assert(p.distance_str[0] == 0);
    /* Telemetry is identical to the v5 packet's -- only the header bytes differ. */
    assert(p.speed_kmh_x10 == 420U);
    assert(p.heading_deg == 90U);
    assert(p.battery_percent == 80U);

    printf("packet_kotlin_fixture_test: OK\n");
    return 0;
}
